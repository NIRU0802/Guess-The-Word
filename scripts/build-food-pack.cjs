const outputFile = path.join(
  process.cwd(),
  "src/data/word-library/packs/food.json"
);

const backupDir = path.join(
  process.cwd(),
  "data/word-library-backups"
);

fs.mkdirSync(path.dirname(outputFile), { recursive: true });
fs.mkdirSync(backupDir, { recursive: true });

if (fs.existsSync(outputFile)) {
  const backupFile = path.join(
    backupDir,
    `food-${new Date().toISOString().replace(/[:.]/g, "-")}.json`
  );

  fs.copyFileSync(outputFile, backupFile);
  console.log(`Previous pack backed up: ${backupFile}`);
}

const uniqueWords = [];
const seen = new Set();

for (const raw of words.split(",")) {
  const word = raw.trim().replace(/\s+/g, " ").toUpperCase();

  if (!word || seen.has(word)) continue;

  seen.add(word);
  uniqueWords.push(word);
}

const pack = {
  id: "food",
  version: 2,
  words: uniqueWords.map((word, index) => ({
    id: `food-${String(index + 1).padStart(4, "0")}`,
    word,
    categoryId: "food",
    language: "en"
  }))
};

fs.writeFileSync(
  outputFile,
  JSON.stringify(pack, null, 2) + "\n",
  "utf8"
);

console.log("\n========== FOOD PACK CREATED ==========");
console.log(`Unique words: ${pack.words.length}`);
console.log(`Output: ${outputFile}`);
console.log("Backup: preserved if an earlier pack existed.");
